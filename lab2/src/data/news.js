function pad(n) {
  return String(n).padStart(2, "0");
}

function buildNews(index) {
  const day = (index % 28) + 1;
  const month = (index % 12) + 1;
  return {
    id: String(index + 1),
    title: `${TOPICS[index % TOPICS.length]} (№${index + 1})`,
    date: `${pad(day)}.${pad(month)}.2026`,
    summary: SUMMARIES[index % SUMMARIES.length],
    content: CONTENTS[index % CONTENTS.length],
    image: `https://picsum.photos/seed/news${index + 1}/400/300`,
  };
}

export function getNewsPage(offset, limit) {
  const end = Math.min(offset + limit, TOTAL_NEWS);
  const items = [];
  for (let i = offset; i < end; i++) {
    items.push(buildNews(i));
  }
  return items;
}

export function getNewsById(id) {
  const n = Number(id);
  if (!Number.isInteger(n) || n < 1 || n > TOTAL_NEWS) {
    return null;
  }
  return buildNews(n - 1);
}